  Future<bool> updateProfile(int trainerId, Map<String, dynamic> data) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final driveService = DriveService();
      Map<String, dynamic> requestData = {};

      if (_currentTrainer != null) {
        requestData = _currentTrainer!.toJson();
      }

      // 1. Merge incoming updates
      requestData.addAll(data);

      // 2. Handle Bio/About mapping
      if (data.containsKey('about')) {
        requestData['bio'] = data['about'];
        requestData.remove('about');
      }

      // 3. Handle Specializations (Names/Maps to IDs)
      final rawSpecs = requestData['specializations'];
      if (rawSpecs is List) {
        final specializationMap = {
          'Weight Loss': 1,
          'Strength Training': 2,
          'Bodybuilding': 3,
          'Rehabilitation': 4,
          'Senior Fitness': 5,
          'Yoga': 6,
          'Athletic Performance': 7,
        };

        final List<int> specIds = rawSpecs
            .map((e) {
              if (e is String) return specializationMap[e];
              if (e is Specialization) {
                return e.id != 0 ? e.id : specializationMap[e.name];
              }
              if (e is Map) {
                final id = e['id'];
                if (id != null && id != 0) return id as int;
                return specializationMap[e['name']];
              }
              return null;
            })
            .where((id) => id != null)
            .cast<int>()
            .toList();

        requestData['specializationIds'] = specIds;
      }

      // 4. Handle Certifications (Upload images and build data for separate API calls)
      final rawCerts =
          requestData['certifications'] ?? requestData['certificates'];
      final List<Map<String, dynamic>> certificatesList = [];

      if (rawCerts is List) {
        for (var certData in rawCerts) {
          int? certId;
          String name = '';
          String organization = '';
          String yearStr = '0';
          String? imageUrl;
          File? imageFile;

          if (certData is TrainerCertification) {
            certId = certData.id;
            name = certData.name;
            organization = certData.organization;
            yearStr = certData.year;
            imageUrl = certData.imageUrl;
            imageFile = certData.image;
          } else if (certData is Certificate) {
            certId = certData.id;
            name = certData.name;
            organization = certData.organization;
            yearStr = certData.year.toString();
            imageUrl = certData.imageUrl;
          } else if (certData is Map<String, dynamic>) {
            certId = certData['id'];
            name = certData['certName'] ?? certData['name'] ?? '';
            organization = certData['issuer'] ?? certData['organization'] ?? '';
            yearStr = (certData['year'] ?? 0).toString();
            imageUrl = certData['imageUrl'];
          }

          if (imageFile != null) {
            imageUrl = await driveService.uploadFile(file: imageFile);
          }

          certificatesList.add({
            'id': certId,
            'certName': name,
            'issuer': organization,
            'year': int.tryParse(yearStr) ?? 0,
            'imageUrl': imageUrl,
            '_hasNewImage': imageFile != null, // Track if image was changed
          });
        }
      }

      // 5. Final Cleanup (Removing read-only or redundant fields)
      requestData.remove('id');
      requestData.remove('email');
      requestData.remove('rating');
      requestData.remove('workouts');
      requestData.remove('plans');
      requestData.remove('specializations');
      requestData.remove('certifications');
      requestData.remove('certificates'); // Handled below via DELETE+POST

      debugPrint('Sending Final Payload to Backend: $requestData');
      await _trainerRepository.updateProfile(trainerId, requestData);

      // 6. Sync certificates: handle deletes, updates, and adds
      //    The backend only supports POST (create) and DELETE for certs.
      //    No PUT endpoint exists for updating individual certs.

      // 6a. Find certs that were REMOVED by the user (exist on backend but not in submitted list)
      final submittedCertIds = certificatesList
          .map((c) => c['id'])
          .where((id) => id != null && id != 0)
          .toSet();
      final existingCerts = _currentTrainer?.certificates ?? [];

      for (final existingCert in existingCerts) {
        if (!submittedCertIds.contains(existingCert.id)) {
          // This cert was removed by the user → DELETE it
          try {
            debugPrint('Deleting removed certificate ${existingCert.id}...');
            await _trainerRepository.deleteCertificate(
              trainerId,
              existingCert.id,
            );
            debugPrint('Certificate ${existingCert.id} deleted');
          } catch (e) {
            debugPrint('Failed to delete cert ${existingCert.id}: $e');
          }
        }
      }

      // 6b. Handle modified and new certs
      for (final certData in certificatesList) {
        final certId = certData['id'];
        final certPayload = Map<String, dynamic>.from(certData);
        certPayload.remove('id');
        final hasNewImage = certData['_hasNewImage'] == true;
        certPayload.remove('_hasNewImage');

        if (certId != null && certId != 0) {
          if (!hasNewImage) {
            // Cert was not changed, skip it
            debugPrint('Certificate $certId unchanged, skipping');
            continue;
          }
          // Existing cert was modified → DELETE old, POST replacement
          try {
            debugPrint('Deleting old certificate $certId for replacement...');
            await _trainerRepository.deleteCertificate(
              trainerId,
              certId is int ? certId : int.parse(certId.toString()),
            );
            debugPrint('Old certificate $certId deleted');
          } catch (e) {
            debugPrint('Failed to delete cert $certId: $e');
            continue; // Don't create duplicate
          }
        }

        // POST new/replacement cert
        try {
          debugPrint('Creating certificate: ${certPayload['certName']}');
          await _trainerRepository.addCertificate(trainerId, certPayload);
          debugPrint('Certificate created successfully');
        } catch (e) {
          debugPrint('Failed to create cert: $e');
        }
      }

      // Refresh details
      await fetchCurrentTrainer(trainerId);

      _isLoading = false;
      notifyListeners();
      return true;
    } on DioException catch (e) {
      debugPrint('Profile Update Error Response: ${e.response?.data}');
      debugPrint('Profile Update Error: $e');
      _isLoading = false;
      _errorMessage = ErrorHandler.getUserFriendlyMessage(e);
      notifyListeners();
      return false;
    } catch (e) {
      debugPrint('Profile Update Error: $e');
      _isLoading = false;
      _errorMessage = ErrorHandler.getUserFriendlyMessage(e);
      notifyListeners();
      return false;
    }
  }

