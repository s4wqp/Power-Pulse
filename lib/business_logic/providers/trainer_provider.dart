  Future<bool> saveDailyNote(
    int trainerId,
    int traineeId,
    String noteTitle,
    String noteContent,
  ) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      // 1. Fetch active subscriptions for trainer
      final subscriptions = await _trainerRepository.getTrainerSubscriptions(
        trainerId,
      );

      // 2. Find ALL subscriptions for this trainee
      final traineeSubs = subscriptions
          .where((s) => s['traineeId'] == traineeId)
          .toList();
      if (traineeSubs.isEmpty) {
        _errorMessage = 'No active subscription found for this trainee.';
        _isLoading = false;
        notifyListeners();
        return false;
      }

      // Sort descending by ID to ensure we target the *newest* subscription!
      traineeSubs.sort((a, b) => (b['id'] as int).compareTo(a['id'] as int));
      final sub = traineeSubs.first;

      if (sub.isEmpty || sub['id'] == null) {
        _errorMessage = 'No active subscription found for this trainee.';
        _isLoading = false;
        notifyListeners();
        return false;
      }

      final subscriptionId = sub['id'] as int;

      // 3. Save the note
      final response = await _trainerRepository.addDailyNote(
        subscriptionId,
        noteTitle,
        noteContent,
      );

      _isLoading = false;
      notifyListeners();
      return response != null;
    } catch (e) {
      _isLoading = false;
      _errorMessage = ErrorHandler.getUserFriendlyMessage(e);
      notifyListeners();
      return false;
    }
  }

  Future<List<Map<String, dynamic>>> fetchNotesForTrainee(
    int trainerId,
    int traineeId,
  ) async {
    try {
      final subscriptions = await _trainerRepository.getTrainerSubscriptions(
        trainerId,
      );
      final traineeSubs = subscriptions
          .where((s) => s['traineeId'] == traineeId)
          .toList();
      if (traineeSubs.isEmpty) return [];

      // Sort descending by ID to ensure we fetch notes for the *newest* subscription!
      traineeSubs.sort((a, b) => (b['id'] as int).compareTo(a['id'] as int));
      final sub = traineeSubs.first;
      if (sub.isEmpty || sub['id'] == null) return [];

      final subId = sub['id'] as int;
      final subDetails = await _trainerRepository.getSubscriptionDetails(subId);

      if (subDetails != null) {
        // Try 'dailyNotes' first
        if (subDetails['dailyNotes'] != null) {
          return List<Map<String, dynamic>>.from(subDetails['dailyNotes']);
        }
        // Fallback to 'notes'
        if (subDetails['notes'] != null) {
          return List<Map<String, dynamic>>.from(subDetails['notes']);
        }
      }

      // Explicit REST fallback if the notes weren't eager-loaded
      try {
        final explicitNotes = await _trainerRepository.getDailyNotes(subId);
        if (explicitNotes != null) {
          return explicitNotes;
        }
      } catch (e) {
        debugPrint('Explicit notes endpoint fallback failed: $e');
      }
    } catch (e) {
      debugPrint('Error fetching notes: $e');
    }
    return [];
  }

