  Future<void> fetchTrainerStats(int trainerId) async {
    try {
      _stats = await _trainerRepository.getTrainerStats(trainerId);

      // If the stats endpoint returned default zeros (e.g. 404 fallback),
      // try to compute from the subscriptions endpoint instead.
      if ((_stats?.totalAmount ?? 0) == 0) {
        await _computeStatsFromSubscriptions(trainerId);
      }

      notifyListeners();
    } catch (e) {
      debugPrint('Error fetching trainer stats: $e');
    }
  }

  /// Fallback: fetch subscriptions for this trainer and sum up plan prices.
  Future<void> _computeStatsFromSubscriptions(int trainerId) async {
    try {
      final response = await _trainerRepository.getTrainerSubscriptions(
        trainerId,
      );
      if (response.isNotEmpty) {
        double totalAmount = 0.0;
        final today = DateTime.now();
        final todayStart = DateTime(today.year, today.month, today.day);
        double todayAmount = 0.0;

        for (final sub in response) {
          final rawPrice =
              sub['priceSnapshot'] ??
              sub['PriceSnapshot'] ??
              sub['planPrice'] ??
              sub['PlanPrice'] ??
              sub['price'] ??
              sub['Price'];

          double parsedPrice = 0.0;
          if (rawPrice is num) {
            parsedPrice = rawPrice.toDouble();
          } else if (rawPrice is String) {
            parsedPrice = double.tryParse(rawPrice) ?? 0.0;
          }
          totalAmount += parsedPrice;

          final startRaw = sub['startDate'] ?? sub['StartDate'];
          if (startRaw is String) {
            final start = DateTime.tryParse(startRaw);
            if (start != null) {
              final startDay = DateTime(start.year, start.month, start.day);
              if (startDay == todayStart) {
                todayAmount += parsedPrice;
              }
            }
          }
        }

        _stats = TrainerStats(
          totalClients: response.length,
          todayAmount: todayAmount,
          totalAmount: totalAmount,
        );
      }
    } catch (e) {
      debugPrint('Error computing stats from subscriptions: $e');
    }
  }

  Future<void> fetchTrainers() async {
    if (_isLoading && _trainers.isNotEmpty) return;

    _isLoading = true;
    _errorMessage = null;
    Future.microtask(() => notifyListeners());

    try {
      final fetchedTrainers = await _trainerRepository.getTrainers();
      // Filter out test trainers generated by the backend testing scripts
      _trainers = fetchedTrainers
          .where(
            (t) =>
                !t.name.toLowerCase().contains('test ai trainer') &&
                !t.name.toLowerCase().startsWith('test'),
          )
          .toList();
      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _isLoading = false;
      if (e is DioException) {
        _errorMessage =
            'Failed to load trainers. The server might be down or unreachable.';
      } else {
        _errorMessage = 'An unexpected error occurred while loading trainers.';
      }
      notifyListeners();
    }
  }

